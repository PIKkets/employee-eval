DROP TABLE IF EXISTS EVALUATION_SCORE;
DROP TABLE IF EXISTS EVALUATOR_MAPPING;
DROP TABLE IF EXISTS EVALUATION_ELEMENT;
DROP TABLE IF EXISTS EMPLOYEE;
DROP TABLE IF EXISTS DEPARTMENT;

CREATE TABLE DEPARTMENT (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE EMPLOYEE (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    department_id BIGINT,
    login_id VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    position VARCHAR(50),
    is_leader BOOLEAN DEFAULT FALSE,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    total_score DOUBLE,
    final_grade VARCHAR(5),
    FOREIGN KEY (department_id) REFERENCES DEPARTMENT(id) ON DELETE SET NULL
);

CREATE TABLE EVALUATION_ELEMENT (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    eval_type VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    weight INT NOT NULL
);

CREATE TABLE EVALUATOR_MAPPING (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    evaluatee_id BIGINT NOT NULL,
    evaluator_id BIGINT NOT NULL,
    eval_type VARCHAR(20) NOT NULL,
    is_anonymous BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (evaluatee_id) REFERENCES EMPLOYEE(id) ON DELETE CASCADE,
    FOREIGN KEY (evaluator_id) REFERENCES EMPLOYEE(id) ON DELETE CASCADE
);

CREATE TABLE EVALUATION_SCORE (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    mapping_id BIGINT NOT NULL,
    element_id BIGINT NOT NULL,
    score INT NOT NULL,
    comment TEXT,
    FOREIGN KEY (mapping_id) REFERENCES EVALUATOR_MAPPING(id) ON DELETE CASCADE,
    FOREIGN KEY (element_id) REFERENCES EVALUATION_ELEMENT(id) ON DELETE CASCADE
);
